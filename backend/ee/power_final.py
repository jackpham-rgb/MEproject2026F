"""Final power design: Uno on its own 9 V battery, servos on the 12 V adapter -> XL4015 buck (5.8 V).

    python3.13 backend/ee/ee_calcs.py      # servo current PWL files (EE/ltspice/pwl/)
    python3.13 backend/ee/power_final.py   # this: ngspice runs + EE/ltspice/power_final_*.cir/.asc + EE/out/power_final.png

Questions it answers:
  1. Does the Uno stay up on a 9 V battery (fresh, and nearly flat at 7.2 V) whatever the servos do?
  2. Can we run without the 1000 uF capacitor? (the XL4015 module has its own ~220 uF output capacitor)
  3. How long does the battery last?
Cases: normal run, MG996R stalled 0.5 s, power-up away from home (servos attached 0.3 s apart).
"""
import os
import shutil
import subprocess

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
LT = os.path.join(ROOT, "EE", "ltspice")
OUT = os.path.join(ROOT, "EE", "out")
PWL = os.path.join(LT, "pwl")

VBUCK, EFF = 5.8, 0.90
I_UNO = 0.045 + (5.0 - 2.0) / 220            # board + status LED (A)
SERVOS = ("turn", "lift", "wrist", "grip")
R_LEAD = {"turn": 0.08, "lift": 0.13, "wrist": 0.13, "grip": 0.13}
R_RAIL = 0.05                                 # buck terminals -> breadboard rail jumpers + contacts
I_STALL = {"turn": 2.5, "lift": 0.7, "wrist": 0.7, "grip": 0.65}   # A (EST, datasheets)
ATTACH_MS = {"turn": 0, "lift": 300, "wrist": 600, "grip": 900}
T_STALL0, T_PU = 3.0, 0.05
BATT = {"fresh": (9.3, 1.5), "low": (7.2, 3.0)}   # 9 V alkaline: open-circuit V, internal resistance (EST)
CASES = [("normal", "Normal run"), ("stall", "MG996R stalled 0.5 s (arm blocked)"), ("powerup", "Power-up away from home")]


def pwl(name):
    a = np.loadtxt(os.path.join(PWL, f"{name}.txt"))
    return a


def inline(a, per=6):
    pts = " ".join(f"{t:.4f} {v:.4f}" for t, v in a)
    return f"PWL({pts})"


def netlist(case, cap, batt, file_pwl=False):
    vb, rb = BATT[batt]
    st = 1 if case == "stall" else 0
    pu = 1 if case == "powerup" else 0
    tend = float(pwl("i_turn")[-1, 0])
    L = [f"* Concept A final power: Uno on a 9 V battery ({batt}), servos on 12 V adapter -> XL4015 {VBUCK} V; "
         f"1000 uF on the rail: {'yes' if cap else 'no'}; case {case}",
         "* Generated by backend/ee/power_final.py",
         "* --- Uno: 9 V battery -> barrel jack -> M7 diode (~1.0 V) -> NCP1117 5 V (dropout ~1.1 V) ---",
         f"VBAT bat 0 {vb}", f"RBAT bat bj {rb}", f"IUNO bj 0 {I_UNO:.4f}",
         "BREG uno5v 0 V=min(5.0,max(V(bj)-2.1,0))", "RREGL uno5v 0 1meg",
         "* --- servos: 12 V 2 A adapter -> XL4015 (averaged), module input 220 uF, output 220 uF ---",
         "VADP adp 0 12.0", "RADP adp vin 0.25", "CIN vin cinn 220u IC=12", "RCIN cinn 0 0.1",
         f"BBUCK bo 0 V={VBUCK}", "VSENSE bo bo2 0", "RBOUT bo2 bk 0.03",
         f"BBIN vin 0 I={VBUCK}*I(VSENSE)/({EFF}*max(V(vin),1))",
         f"COUT bk coutn 220u IC={VBUCK}", "RCOUT coutn 0 0.15",
         "VRAIL bk bkr 0", f"RRAIL bkr rail {R_RAIL}"]
    if cap:
        L += [f"CRAIL rail nc 1000u IC={VBUCK}", "RESR nc 0 0.08"]
    for s in SERVOS:
        node = "bk" if s == "turn" else "rail"          # MG996R power straight from the buck terminals
        src = f"PWL file=pwl/i_{s}.txt" if file_pwl else inline(pwl(f"i_{s}"))
        L += [f"RL_{s} {node} v_{s} {R_LEAD[s]}", f"I_{s} v_{s} 0 {src}",
              f"IPU_{s} v_{s} 0 PULSE(0 {I_STALL[s] * pu} {T_PU + ATTACH_MS[s] / 1000} 1m 1m 0.28 100)"]
    L += [f"ISTALL v_turn 0 PULSE(0 {2.5 * st} {T_STALL0} 1m 1m 0.5 100)", f".tran 1m {tend:.3f} 0 2m uic"]
    return L


def spike_netlist(cap):
    """All four servos start at once (worst inrush): currents step up in 0.1 ms. 10 us resolution. The buck is an
    ideal 5.8 V source behind its 47 uH output inductor (its control loop needs ~0.1-0.5 ms to catch up: EST)."""
    L = ["* Concept A: servo inrush, 1000 uF on the rail: " + ("yes" if cap else "no"),
         f"BBUCK bo 0 V={VBUCK}", "RBO bo bl 0.03", "LBUCK bl bk 47u",
         f"COUT bk coutn 220u IC={VBUCK}", "RCOUT coutn 0 0.15", f"RRAIL bk rail {R_RAIL}"]
    if cap:
        L += [f"CRAIL rail nc 1000u IC={VBUCK}", "RESR nc 0 0.08"]
    for i, s in enumerate(SERVOS):
        node = "bk" if s == "turn" else "rail"
        L += [f"RL_{s} {node} v_{s} {R_LEAD[s]}", f"I_{s} v_{s} 0 PULSE(0 {I_STALL[s]} {1e-3 + i * 0.2e-3} 0.1m 0.1m 8m 20m)"]
    L += [".tran 10u 20m 0 10u uic"]
    return L


def run_spike():
    out = {}
    for cap in (True, False):
        dat = os.path.join(OUT, "_ps.dat"); sp = os.path.join(OUT, "_ps.sp")
        open(sp, "w").write("\n".join(spike_netlist(cap) + [".control", "set noaskquit", "run",
                                       f"wrdata {dat} v(rail) v(v_grip) v(v_turn)", ".endc", ".end"]))
        r = subprocess.run(["ngspice", "-b", sp], capture_output=True, text=True, timeout=600)
        os.remove(sp)
        if r.returncode != 0:
            raise SystemExit("ngspice failed (spike)")
        a = np.loadtxt(dat); os.remove(dat)
        out[cap] = dict(t=a[:, 0], rail=a[:, 1], grip=a[:, 3], turn=a[:, 5])
    open(os.path.join(LT, "power_final_inrush.cir"), "w").write("\n".join(spike_netlist(True) + [".end", ""]))
    return out


def main():
    os.makedirs(OUT, exist_ok=True)
    for case, _ in CASES:
        open(os.path.join(LT, f"power_final_{case}.cir"), "w").write("\n".join(netlist(case, True, "fresh", True) + [".end", ""]))
    if not shutil.which("ngspice"):
        raise SystemExit("ngspice not found: netlists written, no simulation")
    res = {}
    for case, _ in CASES:
        for cap in (True, False):
            for batt in ("fresh", "low"):
                dat = os.path.join(OUT, "_pf.dat")
                deck = netlist(case, cap, batt) + [".control", "set noaskquit", "run",
                       f"wrdata {dat} v(uno5v) v(rail) v(v_turn) v(v_lift) v(v_wrist) v(v_grip) i(vadp) i(vbat)", ".endc", ".end"]
                sp = os.path.join(OUT, "_pf.sp")
                open(sp, "w").write("\n".join(deck))
                r = subprocess.run(["ngspice", "-b", sp], capture_output=True, text=True, timeout=900)
                os.remove(sp)
                if r.returncode != 0 or not os.path.exists(dat):
                    print(r.stdout[-1500:], r.stderr[-1500:])
                    raise SystemExit("ngspice failed")
                a = np.loadtxt(dat); os.remove(dat)
                res[(case, cap, batt)] = dict(t=a[:, 0], uno=a[:, 1], rail=a[:, 3], turn=a[:, 5], lift=a[:, 7], wrist=a[:, 9],
                                              grip=a[:, 11], i_adp=-a[:, 13], i_bat=-a[:, 15])
    rep = ["FINAL POWER DESIGN: Uno on a 9 V battery, servos on 12 V adapter -> XL4015 5.8 V (backend/ee/power_final.py)", "=" * 92,
           "Limits: Uno 5 V >= 4.5 V (16 MHz); servos >= 4.8 V (rated) and <= 6.0 V (MG90S/SG90); 12 V adapter <= 2 A", "",
           f"{'case':34s} {'1000uF':7s} {'battery':8s} {'Uno 5V min':>11s} {'servo min':>10s} {'micro-servo dip':>16s} {'adapter max':>12s}"]
    ok = True
    for case, title in CASES:
        for cap in (True, False):
            for batt in ("fresh", "low"):
                d = res[(case, cap, batt)]
                k = d["t"] > 0.02
                umin = d["uno"][k].min()
                smin = min(d[s][k].min() for s in SERVOS)
                micro = min(d[s][k].min() for s in ("lift", "wrist", "grip"))
                ia = d["i_adp"][k].max()
                good = umin >= 4.5 and ia <= 2.0 and (smin >= 4.8 or case == "stall")
                ok &= good
                rep.append(f"{title:34s} {'yes' if cap else 'NO':7s} {batt:8s} {umin:9.2f} V {smin:8.2f} V {micro:14.2f} V {ia:10.2f} A"
                           + ("" if good else "   <-- check"))
    sp_ = run_spike()
    rep += ["", "FAST INRUSH (all four servos start within 0.6 ms, currents rise in 0.1 ms; 10 us resolution, EST buck response):"]
    for cap in (True, False):
        d = sp_[cap]
        rep.append(f"   1000 uF {'yes' if cap else 'NO ':3s}: micro-servo supply dips to {d['grip'].min():.2f} V, MG996R supply to {d['turn'].min():.2f} V, "
                   f"rings up to {max(d['grip'].max(), d['turn'].max()):.2f} V")
    rep.append("   (the run above averages the servo currents over ms, so the capacitor makes no difference there; it only")
    rep.append("    matters for these fast spikes)")
    life_h = 0.55 / I_UNO
    rep += ["", f"Battery: the Uno + LED draw {I_UNO * 1000:.0f} mA -> a 9 V alkaline (~550 mAh) lasts ~{life_h:.0f} h of power-on time "
            f"(less as it ages). Replace it when it reads < 7.5 V unloaded (the Uno needs ~7.1 V at the jack).",
            "The Uno no longer shares a supply with the servos: a stalled MG996R can't reset it. Grounds MUST still be joined",
            "(Uno GND <-> servo rail GND), or the servo signals have no reference.",
            "Regulator heat on 9 V: (9.3 - 1.0 - 5.0) V x 59 mA = 0.19 W (fine).",
            "", "RESULT: " + ("ALL PASS" if ok else "see the marked rows")]
    open(os.path.join(OUT, "power_final_report.txt"), "w").write("\n".join(rep) + "\n")
    print("\n".join(rep))

    fig, axs = plt.subplots(len(CASES), 1, figsize=(12, 9), sharex=True)
    for ax, (case, title) in zip(axs, CASES):
        for cap, ls in ((True, "-"), (False, "--")):
            d = res[(case, cap, "fresh")]
            ax.plot(d["t"], d["grip"], ls, color="#c0392b", lw=1.1, label=f"gripper servo supply ({'with' if cap else 'WITHOUT'} 1000 µF)")
            ax.plot(d["t"], d["turn"], ls, color="#2f6fdb", lw=1.0, label=f"MG996R supply ({'with' if cap else 'without'} 1000 µF)")
        ax.plot(res[(case, True, "low")]["t"], res[(case, True, "low")]["uno"], color="#0f7c8c", lw=1.4, label="Uno 5 V (9 V battery nearly flat)")
        ax.axhline(4.8, color="#888", ls=":", lw=0.8); ax.axhline(4.5, color="#0f7c8c", ls=":", lw=0.8)
        ax.set_ylim(3.8, 6.2); ax.set_title(title, fontsize=10); ax.set_ylabel("V")
    axs[0].legend(fontsize=7.5, ncol=2, loc="lower left")
    axs[-1].set_xlabel("time (s), firmware run")
    fig.suptitle("Final power: Uno on 9 V battery, servos on 12 V → buck 5.8 V. Solid: with 1000 µF, dashed: without", fontsize=11)
    fig.tight_layout()
    fig.savefig(os.path.join(OUT, "power_final.png"), dpi=120)
    print("wrote EE/out/power_final.png, power_final_report.txt, EE/ltspice/power_final_*.cir")


if __name__ == "__main__":
    main()
