"""One complete PrusaSlicer config per plate (A-E): File > Import > Import Config... and slice. No 3D file changes.

    python3.13 backend/tools/make_plate_inis.py   -> cad/print/settings/plates/plate_A.ini ... plate_E.ini

Each .ini is a FULL config (printer + filament + print), so importing it can't leave anything on a default:
  printer  = PrusaSlicer's own "Creality CR-6 SE (0.4 mm nozzle)" vendor profile (start G-code, bed, limits)
  filament + print = cad/print/settings/concept_a_PETG_prusaslicer.ini (PETG, textured PEI)
                     + the plate's profile from backend/tools/print_economy.py (layer, walls, infill, speeds, supports)
Every file is checked by slicing its plate's STLs with it.
"""
import configparser
import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "backend", "tools"))
import print_economy as E  # noqa: E402

VENDOR = "/usr/share/PrusaSlicer/profiles/Creality.ini"
PRINTER = "printer:Creality CR-6 SE (0.4 mm nozzle)"
OUT = os.path.join(ROOT, "cad", "print", "settings", "plates")


def vendor_printer():
    cp = configparser.RawConfigParser(strict=False, interpolation=None)
    cp.optionxform = str
    with open(VENDOR, encoding="utf-8") as f:
        cp.read_string(f.read())

    def resolve(sec):
        d = {}
        for parent in [p.strip() for p in cp[sec].get("inherits", "").split(";") if p.strip()]:
            d.update(resolve("printer:" + parent))
        d.update({k: v for k, v in cp[sec].items() if k != "inherits"})
        return d
    return resolve(PRINTER)


def base_ini():
    d = {}
    for line in open(E.INI, encoding="utf-8"):
        if "=" in line and not line.lstrip().startswith("#"):
            k, v = line.split("=", 1)
            d[k.strip()] = v.strip()
    d.pop("bed_shape", None)                       # keep the vendor's real CR-6 SE bed
    return d


def main():
    os.makedirs(OUT, exist_ok=True)
    printer = {k: v for k, v in vendor_printer().items() if k not in ("renamed_from", "printer_model", "printer_notes")}
    base = base_ini()
    for name, prof, over, pns, why in E.PLATES:
        letter = name[0]
        s = {**E.PROFILES[prof], **E.SPEED_GLOBAL, **over}
        if s["fill_density"] == "100%":
            s["fill_pattern"] = "rectilinear"
        s.setdefault("support_material", "0")
        s.setdefault("brim_width", "0")
        cfg = {**printer, **base, **s}
        with tempfile.TemporaryDirectory() as d:
            src = os.path.join(d, "in.ini")
            with open(src, "w") as f:
                f.write("".join(f"{k} = {v}\n" for k, v in cfg.items()))
            out = os.path.join(OUT, f"plate_{letter}.ini")
            r = subprocess.run(["prusa-slicer", "--load", src, "--save", out], capture_output=True, text=True, timeout=120)
            if r.returncode or not os.path.exists(out):
                raise SystemExit(f"plate {letter}: {r.stderr[-300:]}")
            with open(out, encoding="utf-8") as f:
                body = f.read()
            head = (f"# Concept A, plate {letter} ({prof}): {', '.join(pns)}\n"
                    f"# PrusaSlicer: File > Import > Import Config... (Ctrl+L), then add the plate's STLs from cad/print/stl and slice.\n"
                    f"# Printer: Creality CR-6 SE 0.4 mm (vendor profile). PETG on textured PEI, no glue.\n")
            with open(out, "w", encoding="utf-8") as f:
                f.write(head + "\n".join(l for l in body.splitlines() if not l.startswith("# generated by")) + "\n")
            gc = os.path.join(d, "o.gcode")
            stls = [E.stl_of(pn) for pn in pns]
            r = subprocess.run(["prusa-slicer", "--export-gcode", "--load", out, "-o", gc] + (["--merge"] if len(stls) > 1 else []) + stls,
                               capture_output=True, text=True, timeout=900)
            ok = os.path.exists(gc)
            if not ok:                                  # PrusaSlicer 2.7 false "path conflict" with organic supports: slice parts one by one
                ok = all(subprocess.run(["prusa-slicer", "--export-gcode", "--load", out, "-o", gc, st], capture_output=True).returncode == 0
                         for st in stls)
                note = "(sliced part by part)"
            else:
                note = ""
            print(f"plate_{letter}.ini  {len(body.splitlines())} settings  slice test: {'OK' if ok else 'FAILED'} {note}")
            if not ok:
                raise SystemExit(1)


if __name__ == "__main__":
    main()
