"""Plates A-E as ready files: cad/print/plates_AE/plate_X.3mf (+ .stl).

    python3.13 backend/tools/make_plate_files.py      (run make_plate_inis.py first)

The .3mf holds the plate's parts as separate objects, laid out like the manual picture, AND the plate's full
PrusaSlicer config (cad/print/settings/plates/plate_X.ini, stored as Metadata/Slic3r_PE.config): open it in
PrusaSlicer and everything is set. The .stl is the same plate as one piece for other slicers (type the
settings from the manual page). Parts come from the unchanged cad/print/stl/ files.
"""
import os
import re
import subprocess
import sys
import tempfile
import zipfile

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "backend", "tools"))
import print_economy as E  # noqa: E402

PL = E.PL
OUT = os.path.join(ROOT, "cad", "print", "plates_AE")
INIS = os.path.join(ROOT, "cad", "print", "settings", "plates")


def main(skip=(), out=OUT):
    """skip: part numbers already printed (left off the plates); a plate with nothing left is not written."""
    os.makedirs(out, exist_ok=True)
    PL.PER_PART = {}                                    # no per-part overrides: the plate config decides everything
    names = {f.split("_")[0]: f[:-4] for f in os.listdir(E.STL)}
    for name, prof, over, pns, why in E.PLATES:
        L = name[0]
        pns = [pn for pn in pns if pn not in skip]
        if not pns:
            continue
        lay = E.plate_layout(pns)
        objs = [(names[pn], t) for pn, t in zip(pns, lay)]
        p3 = os.path.join(out, f"plate_{L}.3mf")
        PL.write_3mf(p3, objs)
        cfg = open(os.path.join(INIS, f"plate_{L}.ini"), encoding="utf-8").read()
        cfg = "".join("; " + l + "\n" for l in cfg.splitlines() if l.strip() and not l.startswith("#"))
        with zipfile.ZipFile(p3, "a", zipfile.ZIP_DEFLATED) as z:
            z.writestr("Metadata/Slic3r_PE.config", "; generated by PrusaSlicer 2.7.2\n" + cfg)
        PL.write_stl(os.path.join(out, f"plate_{L}.stl"), np.concatenate(lay))
        # check: slicing the 3mf alone (no --load) must use the plate's settings
        with tempfile.TemporaryDirectory() as d:
            gc = os.path.join(d, "o.gcode")
            r = subprocess.run(["prusa-slicer", "--export-gcode", "--dont-arrange", "-o", gc, p3], capture_output=True, text=True, timeout=900)
            txt = open(gc, errors="ignore").read() if os.path.exists(gc) else ""
        lh = re.search(r"^; layer_height = (.+)$", txt, re.M)
        ok = lh and lh.group(1) == E.PROFILES[prof]["layer_height"]
        print(f"plate_{L}.3mf  {len(pns)} parts  config inside: {'OK' if ok else 'CHECK'}"
              f"{'' if txt else '  (slice test failed: ' + r.stderr[-200:] + ')'}")


if __name__ == "__main__":
    # python3.13 backend/tools/make_plate_files.py [--skip CA-203,CA-201 --out cad/print/to_print_now]
    a = sys.argv[1:]
    sk = a[a.index("--skip") + 1].split(",") if "--skip" in a else ()
    main(sk, os.path.join(ROOT, a[a.index("--out") + 1]) if "--out" in a else OUT)
